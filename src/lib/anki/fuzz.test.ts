import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { constrainedFuzzBounds, getFuzzFactor, learningIntervalWithFuzz, minimumReviewFuzzInterval, withReviewFuzz } from './fuzz.ts';

test('Anki review fuzz follows its piecewise ranges, transition points, and interval limits', () => {
  const cases = [
    [1, 1, 1000, 1, 1, 1], [2.49, 1, 1000, 2, 2, 2], [2.5, 1, 1000, 2, 3, 4],
    [7, 1, 1000, 5, 7, 9], [17, 1, 1000, 14, 17, 20], [37, 1, 1000, 33, 37, 41],
    [2, 2, 1000, 2, 2, 2], [2, 3, 1000, 3, 4, 4], [2, 3, 3, 3, 3, 3],
    [6.9, 3, 1000, 5, 7, 9], [7, 3, 1000, 5, 7, 9], [7.1, 3, 1000, 5, 7, 9],
    [19.9, 3, 1000, 17, 20, 23], [20, 3, 1000, 17, 20, 23], [20.1, 3, 1000, 17, 20, 23],
    [100, 101, 1000, 101, 105, 108], [100, 1, 99, 92, 96, 99], [100, 97, 103, 97, 100, 103],
  ];
  for (const [interval, minimum, maximum, lower, middle, upper] of cases) {
    assert.equal(withReviewFuzz(interval, minimum, maximum, 0), lower);
    assert.equal(withReviewFuzz(interval, minimum, maximum, 0.5), middle);
    assert.equal(withReviewFuzz(interval, minimum, maximum, 0.99), upper);
  }
});

test('Anki deterministic fuzz mode rounds and clamps without changing its raw interval', () => {
  assert.equal(withReviewFuzz(1.5, 1, 100, null), 2);
  assert.equal(withReviewFuzz(0.1, 1, 100, null), 1);
  assert.equal(withReviewFuzz(101, 1, 100, null), 100);
  assert.deepEqual(constrainedFuzzBounds(1, 3, 2), [2, 2]);
});

test('Anki preserves the previous review interval only when it lies inside the fuzz range', () => {
  assert.equal(minimumReviewFuzzInterval(2.7269483, 4, 36500), 4);
  assert.equal(minimumReviewFuzzInterval(2.7269483, 5, 36500), 0);
  assert.equal(minimumReviewFuzzInterval(4.591988, 4, 36500), 5);
});

test('Anki seeded fuzz matches native Rust rand 0.9.4 vectors', () => {
  // Generated by StdRng::seed_from_u64 with f32 and u32 random_range calls.
  const vectors: [bigint, number, number, number][] = [
    [0n, 0.8014591932296753, 72, 720],
    [1n, 0.8249526023864746, 72, 723],
    [42n, 0.13340973854064941, 62, 620],
    [1000n, 0.9981904029846191, 74, 749],
    [1700000000000n, 0.08262836933135986, 61, 612],
    [18446744073709551615n, 0.1806238889694214, 62, 627],
  ];
  for (const [seed, factor, minute, tenMinutes] of vectors) {
    assert.equal(getFuzzFactor(seed), factor);
    assert.equal(learningIntervalWithFuzz(60, seed), minute);
    assert.equal(learningIntervalWithFuzz(600, seed), tenMinutes);
  }
  assert.equal(getFuzzFactor(1n << 64n), getFuzzFactor(0n));
  assert.equal(learningIntervalWithFuzz(60, null), 60);
  assert.equal(learningIntervalWithFuzz(3, 42n), 3);
  assert.ok(learningIntervalWithFuzz(3600, 42n) < 3900);
});

test('learning due-time fuzz matches actual Anki production-core answers', () => {
  const fixtures = JSON.parse(readFileSync(new URL('../__fixtures__/anki-fuzz-reference.json', import.meta.url), 'utf8')) as {
    cases: { name: string; card: { reps: number; anki: { seedId: number | string } }; appliedLearningSeconds?: Record<string, number> }[];
  };
  let checked = 0;
  for (const fixture of fixtures.cases) {
    if (!fixture.appliedLearningSeconds) continue;
    const seed = BigInt(fixture.card.anki.seedId) + BigInt(fixture.card.reps);
    assert.equal(learningIntervalWithFuzz(60, seed), fixture.appliedLearningSeconds['1'], `${fixture.name}: Again`);
    assert.equal(learningIntervalWithFuzz(600, seed), fixture.appliedLearningSeconds['3'], `${fixture.name}: Good`);
    checked++;
  }
  assert.equal(checked, 6);
});
